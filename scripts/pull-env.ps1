<#
.SYNOPSIS
  Recreates the local .env from the deployed Container App, so a fresh clone on another machine can run,
  test and redeploy the app without copying secrets around by hand.

.DESCRIPTION
  Reads the Container App's environment variables and resolves `secretref:` values from Container App
  secrets (requires `az login` with access to the app, e.g. Contributor on the resource group).
  Deployment-only variables (AZURE_TOKEN_CREDENTIALS) are skipped, because locally the app must fall back
  to your Azure CLI sign-in.

.EXAMPLE
  pwsh ./scripts/pull-env.ps1
  pwsh ./scripts/pull-env.ps1 -Force          # overwrite an existing .env
#>
[CmdletBinding()]
param(
    [string]$ResourceGroup = "pcdotai-agent",
    [string]$AppName = "contoso-insurance-voice-agent",
    [string]$OutFile = (Join-Path $PSScriptRoot "..\.env"),
    [switch]$Force
)

$ErrorActionPreference = "Stop"
$SkipVariables = @("AZURE_TOKEN_CREDENTIALS")

if ((Test-Path $OutFile) -and -not $Force) {
    throw "$OutFile already exists. Use -Force to overwrite it."
}

$envVars = az containerapp show -n $AppName -g $ResourceGroup --query "properties.template.containers[0].env" -o json | ConvertFrom-Json
if ($LASTEXITCODE -ne 0) { throw "Could not read Container App $AppName in $ResourceGroup" }
$secrets = @{}
$secretList = az containerapp secret list -n $AppName -g $ResourceGroup --show-values -o json | ConvertFrom-Json
if ($LASTEXITCODE -ne 0) { throw "Could not read the secrets of $AppName (needs write access to the app)" }
foreach ($s in $secretList) { $secrets[$s.name] = $s.value }

$lines = @(
    "# Generated by scripts/pull-env.ps1 from Container App '$AppName' ($ResourceGroup) on $(Get-Date -Format s)",
    "# Contains a secret (attlassian_api_key). Never commit this file."
)
foreach ($var in $envVars) {
    if ($SkipVariables -contains $var.name) { continue }
    $value = if ($var.secretRef) { $secrets[$var.secretRef] } else { $var.value }
    $lines += "$($var.name)=`"$value`""
}
Set-Content -Path $OutFile -Value $lines -Encoding utf8
Write-Host "Wrote $($envVars.Count - $SkipVariables.Count) settings to $(Resolve-Path $OutFile)"
